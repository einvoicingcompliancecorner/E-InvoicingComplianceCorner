import json

OUT_FILE = "043_norway_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/norway_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Norway stories covering the March 2026 acceleration")
lines.append("-- of the B2B mandate to January 2027, the June 2026 formal legal")
lines.append("-- enactment (Law-2026-06-19-39), and the ongoing exploration of")
lines.append("-- expansion beyond B2B (e-receipts, B2C, software regulation).")
lines.append("-- First stories for Norway, identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official Skatteetaten portal.")
lines.append("-- Generated by migrations/generate_norway_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
