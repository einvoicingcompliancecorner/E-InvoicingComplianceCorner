#!/usr/bin/env node
// partner-branding.mjs — the partner mark, and the four ways it can go wrong.
//
//   node tests/partner-branding.mjs
//
// A subscriber on a partner's email domain gets that partner's mark on the
// first page of the PDFs they generate. Four of the five checks here exist
// because the failure they guard against is INVISIBLE from the outside: an
// unbranded document looks exactly like a reader who switched the
// preference off, so nothing about a broken lookup, a missing file or a
// mis-sized logo announces itself. Nobody would report these.
//
// ---- WHY THE SIZING IS MEASURED AND NOT ASSERTED LEXICALLY -------------
//
// The mark was first specified as "40mm wide", which is right for exactly
// one asset: the Tradeshift wordmark is 6.09:1, so 40mm across happens to
// be 6.6mm tall. A checking rule that reads the CSS and finds "40mm" would
// pass on a square logo printing 40mm x 40mm in the corner of a compliance
// document. So this renders three aspect ratios in a real browser and
// measures what comes out, which is the only version of this check that
// fails on the partner nobody has added yet.
import { suite, launch } from "./lib/browser.mjs";
import { openReplayDb } from "./lib/replay-db.mjs";
import { existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { partnerForEmail, domainOf, partnerMarkHtml, PARTNER_MARK_CSS } from "../shared/partners.mjs";

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const t = suite("partner branding");
const { d1 } = await openReplayDb();
const all = async (sql, ...args) => (await d1.prepare(sql).bind(...args).all()).results || [];

// ---- 1. the table says what the migration claims ----------------------
const partners = await all("SELECT * FROM partners");
t.check("a partner is registered", partners.length >= 1, `${partners.length} rows`);
t.check("Tradeshift is active, with a dark mark and no unapproved light one",
  partners.some((p) => p.slug === "tradeshift" && p.active === 1
    && p.mark_dark && p.mark_light === null));

// ---- 2. every mark path resolves to a file that exists -----------------
//
// SQL cannot see the filesystem, so without this the chain can hold a
// perfectly valid row pointing at a logo nobody committed. The reader
// then gets a broken-image glyph in the masthead of a document they were
// about to send to their tax authority. Same shape as the check in
// map-tiles-agree.mjs that every tracked country resolves to a topology.
let missing = [];
for (const p of partners) {
  for (const path of [p.mark_dark, p.mark_light].filter(Boolean)) {
    if (!existsSync(join(REPO, path))) missing.push(`${p.slug}: ${path}`);
  }
}
t.check("every mark path resolves to a committed file", missing.length === 0, missing.join("; "));

// ---- 3. the lookup, and the lookalike domain --------------------------
//
// The suffix-match trap is the reason partner_domains stores exact
// domains. If the query ever becomes a LIKE or an endsWith, the third
// assertion below is the one that fails, and it fails loudly.
t.check("a partner address resolves",
  (await partnerForEmail(d1, "someone@tradeshift.com"))?.slug === "tradeshift");
t.check("an ordinary address resolves to nobody",
  (await partnerForEmail(d1, "someone@example.com")) === null);
t.check("a lookalike domain resolves to nobody",
  (await partnerForEmail(d1, "attacker@tradeshift.com.example.net")) === null);
t.check("case and whitespace in the address do not matter",
  (await partnerForEmail(d1, "  Someone@TRADESHIFT.com  ".trim()))?.slug === "tradeshift");
t.check("an address with an @ in the local part reads the real domain",
  domainOf('"a@b"@tradeshift.com') === "tradeshift.com", domainOf('"a@b"@tradeshift.com'));
t.check("a malformed address resolves to nobody",
  (await partnerForEmail(d1, "not-an-address")) === null);

// ---- 4. the label says what was decided --------------------------------
//
// "In association with" was the original wording and was changed
// deliberately: it asserts a relationship between this site and the
// partner, on a site whose value is that its judgements are its own.
// "Generated by" asserts only who produced this copy of this file.
const strings = await all(
  "SELECT lang, value FROM translations WHERE key IN ('guides.doc.partnerBy','pdf.partnerBy')");
t.check("the mark's label is translated into all four languages, for both documents",
  strings.length === 8, `${strings.length} rows`);
t.check("no language claims an association",
  !strings.some((r) => /associat|asociac|zusammenarbeit/i.test(r.value)),
  strings.filter((r) => /associat|asociac/i.test(r.value)).map((r) => r.lang).join(","));

// ---- 5. the mark is fitted to a box, at every aspect ratio -------------
//
// 40mm x 10mm at 96dpi is 151.2 x 37.8 CSS pixels. A wide wordmark should
// bind on width and a square one on height; neither may exceed the box in
// either direction, and a mark that fits should never be scaled UP to
// fill it.
const MM = 96 / 25.4;
const BOX_W = 40 * MM, BOX_H = 10 * MM;
const RATIOS = [
  { name: "6.09:1 wordmark", r: 6.09, binds: "width" },
  { name: "3:1 lockup", r: 3, binds: "height" },
  { name: "1:1 badge", r: 1, binds: "height" },
];

const browser = await launch();
const page = await browser.newPage({ viewport: { width: 900, height: 400 } });
t.watch(page);

// A one-pixel SVG per ratio, so the browser does the fitting from a real
// intrinsic size rather than from anything this file asserts.
const svg = (r) =>
  `data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r * 100} 100"><rect width="${r * 100}" height="100" fill="#000"/></svg>`)}`;

await page.setContent(`<style>${PARTNER_MARK_CSS}</style>`
  + RATIOS.map((x, i) => `<div class="pmark" id="m${i}"><span>Generated by</span>`
    + `<img src="${svg(x.r)}"></div>`).join(""));
await page.waitForTimeout(400);

const measured = await page.$$eval(".pmark img", (imgs) =>
  imgs.map((i) => ({ w: i.getBoundingClientRect().width, h: i.getBoundingClientRect().height })));

let overflow = [], wrongBind = [];
RATIOS.forEach((x, i) => {
  const m = measured[i];
  if (!m) { overflow.push(`${x.name}: did not render`); return; }
  // Half a pixel of tolerance: sub-pixel layout, not a real difference.
  if (m.w > BOX_W + 0.5 || m.h > BOX_H + 0.5) {
    overflow.push(`${x.name}: ${m.w.toFixed(1)}x${m.h.toFixed(1)}px exceeds ${BOX_W.toFixed(1)}x${BOX_H.toFixed(1)}`);
  }
  const boundBy = Math.abs(m.w - BOX_W) < 1 ? "width" : Math.abs(m.h - BOX_H) < 1 ? "height" : "neither";
  if (boundBy !== x.binds) wrongBind.push(`${x.name}: bound by ${boundBy}, expected ${x.binds}`);
});

t.check("no aspect ratio escapes the 40 x 10mm box", overflow.length === 0, overflow.join("; "));
t.check("wide marks bind on width and tall ones on height", wrongBind.length === 0, wrongBind.join("; "));

// And the thing the original 40mm-wide rule would have got wrong: a square
// logo must not print taller than the wordmark does.
const tallest = Math.max(...measured.map((m) => m.h));
t.check("the tallest mark is no taller than the box", tallest <= BOX_H + 0.5,
  `${tallest.toFixed(1)}px vs ${BOX_H.toFixed(1)}px`);

// ---- 6. no mark, no markup --------------------------------------------
//
// Almost every reader has no partner, and for them the masthead must be
// byte-identical to what it has always been rather than carrying an empty
// container that shifts the layout by a few points.
t.check("a reader with no partner gets no markup at all",
  partnerMarkHtml(null, "Generated by") === ""
  && partnerMarkHtml({ displayName: "X" }, "Generated by") === "");

await browser.close();
process.exit(t.report() ? 0 : 1);
