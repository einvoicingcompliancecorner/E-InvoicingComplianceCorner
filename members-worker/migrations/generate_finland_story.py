import json

OUT_FILE = "022_finland_story.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/finland_story.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = ["-- New story: Finland's Peppol Advanced Ordering mandate for Central",
         "-- Government, contrasted with the continued absence of any domestic",
         "-- B2B mandate. Completes the end-to-end new-country rollout per",
         "-- ADDING-A-COUNTRY.md's Phase 6 checklist. Sourced to the official",
         "-- Valtiokonttori (Finnish State Treasury) e-invoicing portal.",
         "-- Generated by migrations/generate_finland_story.py.", ""]

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")
print(f"Written {len(stories)} story to {OUT_FILE}")
