"""Generate migration 646 -- Dan's Middle East / Africa removals.

Run:  python3 migrations/gen_mea_tile_removals.py
Writes: migrations/646_mea_tile_removals.sql

Dan, 25 August 2026, working the regions in turn. 644 was his sweep of
Europe and the Americas; this is Middle East / Africa. Same method: he
reads the page, names the tile, and the list is resolved against the live
rows before anything is written.

---- WHAT THESE HAVE IN COMMON ---------------------------------------

Every one is a dated milestone that says only what a headline tile now
says, which is the exact class 643's rules could not see because they
kept anything carrying a year:

  Egypt        "2023 / B2B fully in force"       beside B2B ACTIVE
  Jordan       "Apr 2025 / Full B2B/B2G/B2C..."  beside three ACTIVE rows
  Kenya        two TIMS/eTIMS rollout dates      beside B2B ACTIVE
  Nigeria      "1 Aug 2025 / MBS goes live"      beside the mandate tile
  Saudi Arabia "2021 / Phase 1 live since"       beside B2B ACTIVE

The dates are not lost: every one of them is in the compliance timeline
further down the same page, which is where a sequence of events belongs.
The strip is for the facts a reader needs before deciding whether the page
applies to them at all.

QATAR'S SECOND TILE IS THE ODD ONE and is here on Dan's judgement rather
than by this rule. "None yet / Qatar has not yet implemented VAT" is true
and duplicates nothing -- it is simply not what the strip is for. A tile
explaining that a country has no VAT sits oddly above four tiles about
e-invoicing obligations that therefore cannot exist yet; the mandate tile
already reads NO MANDATE and the page's prose covers the reason.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# (country, english_value, english_label) -- resolved against live rows.
REMOVE = [
    ('Egypt', '2023', 'B2B fully in force'),
    ('Jordan', 'Apr 2025', 'Full B2B/B2G/B2C enforcement since'),
    ('Kenya', '30 Nov 2022', 'Electronic tax invoices mandatory for all VAT-registered businesses (TIMS)'),
    ('Kenya', '1 Sep 2023', 'Obligation extends to ALL businesses, including non-VAT-registered (eTIMS)'),
    ('Nigeria', '1 Aug 2025', "MBS goes live -- MTN, Huawei and IHS transmit Nigeria's first cleared e-invoices"),
    ('Qatar', 'Draft stage', 'E-invoicing law status'),
    ('Qatar', 'None yet', 'Qatar has not yet implemented VAT'),
    ('Saudi Arabia', '2021', 'Phase 1 live since'),
]


def q(s):
    return "'" + s.replace("'", "''") + "'"


HEADER = """-- ================================================================
-- Dan's Middle East / Africa tile removals.
-- ================================================================
--
-- Generated by gen_mea_tile_removals.py -- edit that, not this.
--
-- The third pass. 643 swept by rule; 644 was Dan's Europe/Americas list;
-- this is his Middle East / Africa list. All eight are dated milestones
-- restating a headline tile -- Egypt's "2023 / B2B fully in force" beside
-- a B2B tile reading ACTIVE, Saudi Arabia's "2021 / Phase 1 live since"
-- beside the same. The dates survive in the compliance timeline below,
-- which is where a sequence of events belongs.
--
-- Qatar's "None yet / Qatar has not yet implemented VAT" is the exception
-- and is here on judgement: it duplicates nothing, it is just not what
-- this strip is for.
-- ================================================================
"""


def sql():
    out = [HEADER, "-- ---- the removals -------------------------------------------------"]
    for country, value, label in REMOVE:
        out.append(f"\n-- {country}: {value} / {label}")
        out.append(
            "DELETE FROM deep_dive_stat_translations WHERE stat_id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    JOIN deep_dive_stat_translations t ON t.stat_id = ds.id AND t.lang = 'en'\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_label = {q(label)});")
        out.append(
            "DELETE FROM deep_dive_stats WHERE id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    LEFT JOIN deep_dive_stat_translations t ON t.stat_id = ds.id\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_id IS NULL);")

    out.append(f"""
-- ---- what this migration claims it did ------------------------------

-- {len(REMOVE)} tiles named above, from 287, leaving 279.
-- ASSERT: SELECT count(*) FROM deep_dive_stats = 279

-- Every language went with them; no orphaned translation rows.
-- ASSERT: SELECT count(*) FROM deep_dive_stat_translations t LEFT JOIN deep_dive_stats ds ON ds.id = t.stat_id WHERE ds.id IS NULL = 0

-- THE FLOOR STILL HOLDS AT TWO, and this pass does not test it: the
-- lowest any affected country reaches is three (Egypt, Jordan, Kenya,
-- Qatar). Kenya and Qatar each lose two tiles, which is why it was worth
-- checking rather than assuming.
-- ASSERT: SELECT (SELECT count(*) FROM (SELECT country_id FROM deep_dive_stats GROUP BY country_id HAVING count(*) < 3)) = 1
""")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    out = os.path.join(HERE, "646_mea_tile_removals.sql")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(sql())
    print(f"{out}: {len(REMOVE)} tiles")
