import json

OUT_FILE = "014_slovakia_spain_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/slovakia_spain_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 2 additional Slovakia stories (FAQ/penalties, national")
lines.append("-- conference) and 3 new Spain stories (Royal Decree approval, AEAT")
lines.append("-- exchange guidance, VERI*FACTU vs Crea y Crece timeline clarification —")
lines.append("-- Spain previously had zero dedicated stories, only a passing mention")
lines.append("-- in a multi-country outlook piece). Sourced to the official Slovak")
lines.append("-- Financial Administration and Spanish AEAT portals. Clean content")
lines.append("-- only, relying on the auto-rendered source/deep-dive link system.")
lines.append("-- Generated by migrations/generate_sk_es_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
