import json

OUT_FILE = "012_germany_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/germany_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: three real, sourced newsletter stories covering Germany's")
lines.append("-- e-invoicing mandate developments through 2026 ahead of the 1 January")
lines.append("-- 2027 issuance deadline: GEBA addressing for Peppol, practical guidance")
lines.append("-- on format errors and validation responsibility, and June's summit")
lines.append("-- confirmation that the rollout remains on track. Clean content only —")
lines.append("-- no manually embedded source or deep-dive links, since both are now")
lines.append("-- auto-rendered by renderIssue() from source_url and story_countries.")
lines.append("-- Generated by migrations/generate_germany_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
