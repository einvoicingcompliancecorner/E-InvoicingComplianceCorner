import json

OUT_FILE = "045_singapore_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/singapore_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Singapore stories covering the February 2026")
lines.append("-- Committee of Supply confirmation extending GST InvoiceNow to all")
lines.append("-- GST-registered businesses by April 2031, the April 2026 milestone")
lines.append("-- for all new voluntary registrants, and the mid-2026 process for")
lines.append("-- existing businesses to confirm their specific deadline. First")
lines.append("-- stories for Singapore, identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official IRAS portal.")
lines.append("-- Generated by migrations/generate_singapore_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
