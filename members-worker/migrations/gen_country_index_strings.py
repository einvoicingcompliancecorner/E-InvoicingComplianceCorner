"""Generate migration 642 — the words above the crawlable country index.

Run:  python3 migrations/gen_country_index_strings.py
Writes: migrations/642_country_index_strings.sql, and patches i18n/*.json.

The index is seventy real anchors at the foot of the tracker, added
because the board is built by JavaScript and a crawler that does not
render saw the site's primary page as 718 words with no link to any
country page -- 42 of which were in neither the sitemap nor any anchor
anywhere on the site.

IT IS A READER-FACING FEATURE TOO, WHICH IS WHY IT NEEDS WORDS. A list
of seventy links under a bare heading is a sitemap someone forgot to
hide. The intro says what the links lead to, so a person scanning for a
jurisdiction knows the destination is a full briefing rather than a
filtered board view. Written for the reader; the crawler benefits either
way.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
I18N = os.path.join(REPO, "i18n")
LANGS = ["en", "de", "fr", "es"]

S = {
    "index.heading": {
        "en": "All jurisdictions",
        "de": "Alle Jurisdiktionen",
        "fr": "Toutes les juridictions",
        "es": "Todas las jurisdicciones",
    },
    "index.intro": {
        "en": "Every country this tracker covers, with its next dated milestone. Each links to a full briefing: the timeline, the format, registration steps and penalties.",
        "de": "Jedes Land dieses Trackers mit dem nächsten datierten Meilenstein. Jeder Eintrag führt zu einem vollständigen Briefing: Zeitplan, Format, Registrierung und Sanktionen.",
        "fr": "Tous les pays suivis par ce tracker, avec leur prochaine échéance datée. Chaque entrée mène à un dossier complet : calendrier, format, démarches et sanctions.",
        "es": "Todos los países que cubre este rastreador, con su próximo hito con fecha. Cada enlace lleva a un informe completo: calendario, formato, registro y sanciones.",
    },
}


def q(s):
    return "'" + s.replace("'", "''") + "'"


def check():
    problems = []
    for key, vals in S.items():
        for lang in LANGS:
            if not vals.get(lang):
                problems.append(f"{key}: no {lang}")
    if problems:
        raise SystemExit("REFUSING TO GENERATE:\n  " + "\n  ".join(problems))


HEADER = """-- ================================================================
-- The words above the crawlable country index.
-- ================================================================
--
-- Generated by gen_country_index_strings.py -- edit that, not this.
--
-- Migration 642 exists because of a finding in the 24 August SEO audit:
-- the tracker serves 718 words of indexable HTML and, until now, NO
-- link to any of the seventy country pages. The board is built from a
-- JavaScript array; DEEP_DIVES is injected as a JS object literal; the
-- board container ships empty. Forty-two of the seventy deep dives were
-- in neither sitemap.xml nor any anchor anywhere on the site, each
-- carrying a thousand words of sourced prose that nothing could crawl
-- to.
--
-- The index is the fix, and these are the two strings above it. They
-- are translated because the index is a reader-facing navigation aid
-- and not only a crawler aid -- the country LABELS are server-rendered
-- in English to match the canonical and translated client-side after
-- load, but the heading and intro are page chrome and belong with every
-- other translated string on this site.
-- ================================================================
"""


def sql():
    lines = [HEADER, "-- ---- the strings ----------------------------------------------------"]
    for key in sorted(S):
        for lang in LANGS:
            lines.append(
                "INSERT OR REPLACE INTO translations (namespace, key, lang, value)\n"
                f"  VALUES ('tracker', {q(key)}, '{lang}', {q(S[key][lang])});")
    lines.append(f"""
-- ---- what this migration claims it did ------------------------------

-- ASSERT: SELECT count(*) FROM translations WHERE namespace = 'tracker' AND key LIKE 'index.%' = {len(S) * len(LANGS)}

-- ---- and what must stay true afterwards -----------------------------

-- FOUR LANGUAGES OR NONE.
-- ASSERT ALWAYS: SELECT count(*) FROM (SELECT key FROM translations WHERE namespace = 'tracker' AND key LIKE 'index.%' GROUP BY key HAVING count(DISTINCT lang) != 4) = 0

-- AND THE INDEX HAS SOMETHING TO INDEX. The list is built from
-- countries with a slug; if that set ever empties, the tracker renders
-- an index heading over nothing. Asserted here rather than in the
-- renderer because the renderer's own guard falls back to the static
-- page, which would hide it.
--
-- WRAPPED IN A SUBQUERY ON PURPOSE. The runner splits on the LAST
-- comparison operator in the line, so the natural-looking
-- `... code != 'EU' >= 50` would be read as a query ending `!= 'EU'`
-- compared against 50 -- which is a different question with a
-- plausible-looking answer. The parenthesised form leaves exactly one
-- operator outside the SQL. Caught by the runner refusing the first
-- version of this line.
-- ASSERT ALWAYS: SELECT (SELECT count(*) FROM countries WHERE slug IS NOT NULL AND code != 'EU') >= 50
""")
    return "\n".join(lines) + "\n"


def patch_i18n():
    for lang in LANGS:
        path = os.path.join(I18N, f"{lang}.json")
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        node = doc.setdefault("index", {})
        for key, vals in S.items():
            node[key.split(".", 1)[1]] = vals[lang]
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(doc, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        print(f"  i18n/{lang}.json: index.heading, index.intro")


if __name__ == "__main__":
    check()
    out = os.path.join(HERE, "642_country_index_strings.sql")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(sql())
    print(f"{out}: {len(S)} keys x {len(LANGS)} languages")
    patch_i18n()
