// ================================================================
// PARTNER BRANDING — resolving a reader's partner from their address
// ================================================================
//
// A subscriber whose email domain belongs to a partner organisation may
// have that partner's mark placed on the PDFs they generate. This module
// is the single place that decides who a partner is; both Workers import
// it so the answer cannot differ between the page that offers the
// preference and the page that acts on it.
//
// THREE THINGS THIS DELIBERATELY IS NOT:
//
// It is not authentication. The address arrives from a verified session
// before this is called, and nothing here is trusted to gate anything --
// the worst a wrong answer can do is put a logo on a document.
//
// It is not a suffix match. `tradeshift.com` is a row; `tradeshift.com`
// as a SUFFIX would also match `tradeshift.com.example.net`, which anyone
// can register. Every domain a partner uses is listed explicitly. That
// costs a row per domain and closes off a class of surprise entirely.
//
// It is not the site palette. Phase one places a mark on two PDFs and
// nothing else. The palette lives behind the same partner row when it is
// built, which is why the palette table exists from the first migration
// even though nothing reads it yet.

/** The domain half of an address, lowercased, or "" if there isn't one.
 *
 *  Takes the LAST @, not the first. Quoted local parts may legally
 *  contain one -- `"a@b"@example.com` is a valid address whose domain is
 *  example.com -- and splitting on the first would hand back `b"`. Rare
 *  to the point of never, but the rare case here fails by branding the
 *  wrong reader, and the fix is one character. */
export function domainOf(email) {
  const at = String(email || "").lastIndexOf("@");
  if (at < 0) return "";
  return String(email).slice(at + 1).trim().toLowerCase();
}

/** The partner for an address, or null.
 *
 *  Returns null for every ordinary failure -- no address, no domain, no
 *  match, an inactive partner, a database that would not answer. The
 *  caller's job is then to render the document exactly as it renders
 *  today, which is why this never throws: an unbranded guide is correct,
 *  and a five-hundred on the guide route is not. */
export async function partnerForEmail(db, email) {
  const domain = domainOf(email);
  if (!db || !domain) return null;
  try {
    const row = await db
      .prepare(
        `SELECT p.slug, p.display_name, p.mark_dark, p.mark_light, p.cta_url
           FROM partner_domains d
           JOIN partners p ON p.id = d.partner_id
          WHERE d.domain = ? AND p.active = 1
          LIMIT 1`,
      )
      .bind(domain)
      .first();
    if (!row) return null;
    return {
      slug: row.slug,
      displayName: row.display_name,
      markDark: row.mark_dark,
      // Null until a partner supplies a reverse lockup. Nothing in phase
      // one reads it; the site palette will, and it must not fall back to
      // the dark mark on a dark ground.
      markLight: row.mark_light || null,
      // Where the partner's own call-to-action points. Added 28 August
      // when Dan asked whether the carousel slide's link was stored
      // against the partner rather than written into a page. It is now.
      // The tracker still carries a copy, because it is a static asset
      // and cannot query D1 -- tests/partner-branding.mjs asserts the two
      // are identical, so neither can move without the other.
      ctaUrl: row.cta_url || null,
    };
  } catch (err) {
    console.log(`partnerForEmail: lookup failed for ${domain}: ${(err && err.message) || err}`);
    return null;
  }
}

/** The mark, as a block for the top right of a document's first page.
 *
 *  SIZED AS A BOX, NOT A WIDTH, and that is the whole reason this helper
 *  exists rather than an inline <img> at each call site.
 *
 *  The first version of this was specified as "40mm wide", measured
 *  against the Tradeshift wordmark. That asset is 6.09:1, so 40mm across
 *  happens to be 6.6mm tall and looks right. Nothing obliges the next
 *  partner's file to be that shape: at 3:1 the same rule gives a mark
 *  twice as tall, and a square lockup would print 40mm x 40mm -- a sixth
 *  of the page, in the corner of a compliance document.
 *
 *  max-width AND max-height, with the aspect ratio preserved, makes the
 *  rule shape-independent. Tradeshift still lands at 40 x 6.6mm because
 *  width binds first; a 3:1 mark lands at 30 x 10mm and a square one at
 *  10 x 10mm. Whoever adds the second partner does not have to think
 *  about this, which is the point.
 *
 *  `label` is passed in already translated. It says GENERATED BY, not "in
 *  association with": the site's judgements are its own, and the only
 *  thing being claimed is who produced this copy of this file. */
export function partnerMarkHtml(partner, label, origin = "") {
  if (!partner || !partner.markDark) return "";
  const src = `${origin}/${String(partner.markDark).replace(/^\/+/, "")}`;
  const alt = String(partner.displayName || "").replace(/"/g, "&quot;");
  return `<div class="pmark"><span>${label}</span>`
    + `<img src="${src}" alt="${alt}" width="151" height="25"></div>`;
}

/** The CSS the block above needs, in print units.
 *
 *  40mm x 10mm is the box. `object-fit:contain` does the fitting and
 *  `object-position:right bottom` sits the mark on the masthead's
 *  baseline, so a short wide mark and a tall narrow one both align with
 *  the title beside them rather than floating at different heights. */
export const PARTNER_MARK_CSS = `
.pmark{display:flex;flex-direction:column;align-items:flex-end;gap:2px;flex:none}
.pmark span{font-family:'IBM Plex Mono',monospace;font-size:6pt;letter-spacing:1.1px;
  text-transform:uppercase;color:#8a8a8a;line-height:1}
.pmark img{max-width:40mm;max-height:10mm;width:auto;height:auto;
  object-fit:contain;object-position:right bottom;display:block}
`;
