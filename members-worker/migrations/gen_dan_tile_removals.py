"""Generate migration 644 -- the removals Dan reviewed by hand.

Run:  python3 migrations/gen_dan_tile_removals.py
Writes: migrations/644_dan_tile_removals.sql

Migration 643 removed 43 tiles by RULE. Dan then read the pages and sent a
list of 24 more, by hand, on 25 August. This is that list.

---- WHY A SECOND PASS, AND WHY HIS BEATS MINE ------------------------

643's rules could only see a duplicate when the two texts looked alike:
"8 yrs / Archive requirement" beside an 8 yrs tile. It kept anything
carrying a year, on the principle that a year is a milestone. That rule
saved Latvia from being emptied, and it was right about Indonesia's
Coretax date -- but it is blind to the case where a DATED tile still says
only what a tile now says. "2014 / B2G mandate in force" carries a year
and adds nothing to a B2G tile already reading ACTIVE; the date is in the
timeline below it. A rule cannot tell those apart. A person reading the
page can.

So: rules for the mechanical sweep, a human for the judgement. Both lists
are written down rather than merged, so it stays clear which removals were
reasoned about and which were pattern-matched.

---- ONE OF THESE RESOLVES A CONTRADICTION ---------------------------

Belgium's "7 yrs / Archive requirement" was one of the three tiles 643
HELD BACK because the stat strip and the headline tile disagreed (7 vs
10). Deleting it then would have decided the contradiction in the tile's
favour with nobody checking. Dan has now checked, and 10 stands. Romania
(10 vs 5) and China (10-30 vs 30) are still open.

---- MATCHED ON COUNTRY + ENGLISH LABEL ------------------------------

Same as 643, for the same reason: stat ids are insertion-ordered and not
guaranteed identical between the replay fixture and production. Every one
of the 24 was matched against the live row before this file was written --
three of them (Finland, Portugal, Sweden) split the sentence differently
from Dan's note, as value "No B2B" plus label "mandate -- yet", and would
have silently matched nothing if the value had been trusted.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# (country, english_value, english_label) -- Dan's list, resolved against
# the real rows. Value is recorded for the audit trail; the DELETE matches
# on country + label, which is unique.
REMOVE = [
    ('Austria', '2014', 'B2G mandate in force'),
    ('Belgium', '7 yrs', 'Archive requirement'),
    ('Belgium', '2028', 'E-reporting go-live'),
    ('Croatia', '20th', 'Monthly e-report deadline'),
    ('Cyprus', '2019/2020', 'B2G receive mandate in force'),
    ('Czech Republic', '2016', 'B2G receive mandate in force'),
    ('Estonia', '1 Jul 2019', 'B2G e-invoicing mandatory for the public sector'),
    ('Finland', 'No B2B', 'mandate — none confirmed'),
    ('Greece', 'Sep 2025', 'B2G fully mandatory'),
    ('Greece', '2 Mar 2026', 'B2B Phase 1 (in force)'),
    ('Hungary', '1 Jul 2018', 'RTIR real-time invoice-data reporting launches'),
    ('Hungary', '1 Jul 2025', 'First real e-invoicing mandate begins (energy/water B2B)'),
    ('Ireland', '2018', 'OGP named Irish Peppol Authority'),
    ('Latvia', '1 Jan 2025', 'B2G e-invoicing: all companies must issue structured e-invoices to government'),
    ('Latvia', '1 Jan 2026', 'Mandatory e-invoice data reporting to VID begins (B2G/G2G/G2B)'),
    ('Lithuania', '1 Jul 2017', 'B2G e-invoicing mandatory for all public procurement'),
    ('Luxembourg', '2023', 'B2G fully in force'),
    ('Netherlands', '2017/2019', 'B2G mandate in force'),
    ('Norway', 'Jun 2026', 'Law formally enacted'),
    ('Portugal', 'No B2B', 'mandate — yet'),
    ('Serbia', '1 Jan 2023', 'B2B e-invoicing (issuance and receipt) becomes mandatory nationwide'),
    ('Slovenia', '1 Jan 2015', 'Public sector required to receive e-invoices (ZOPSPU/ZOPSPU-A)'),
    ('Spain', '2015', 'B2G (FACe) mandatory since'),
    ('Sweden', 'No B2B', 'Domestic mandate — none yet'),
]


def q(s):
    return "'" + s.replace("'", "''") + "'"


HEADER = """-- ================================================================
-- The tile removals Dan reviewed by hand.
-- ================================================================
--
-- Generated by gen_dan_tile_removals.py -- edit that, not this.
--
-- 643 swept 43 tiles by rule and deliberately kept anything carrying a
-- year, because a year is usually a milestone. These 24 are the cases
-- where a dated tile still says only what a headline tile now says --
-- "2014 / B2G mandate in force" beside a B2G tile reading ACTIVE, with
-- the date already in the timeline below. No rule separates those from a
-- real milestone; a person reading the page does.
--
-- Belgium's "7 yrs / Archive requirement" is here too. 643 held it back
-- because it CONTRADICTED the headline tile (7 vs 10) and deleting one
-- side would have settled that silently. Dan has settled it: 10 stands.
-- ================================================================
"""


def sql():
    out = [HEADER, "-- ---- the removals -------------------------------------------------"]
    for country, value, label in REMOVE:
        out.append(f"\n-- {country}: {value} / {label}")
        out.append(
            "DELETE FROM deep_dive_stat_translations WHERE stat_id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    JOIN deep_dive_stat_translations t ON t.stat_id = ds.id AND t.lang = 'en'\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_label = {q(label)});")
        out.append(
            "DELETE FROM deep_dive_stats WHERE id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    LEFT JOIN deep_dive_stat_translations t ON t.stat_id = ds.id\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_id IS NULL);")

    out.append(f"""
-- ---- what this migration claims it did ------------------------------

-- {len(REMOVE)} tiles named above, from 311, leaving 287.
-- ASSERT: SELECT count(*) FROM deep_dive_stats = 287

-- Every language went with them; no orphaned translation rows.
-- ASSERT: SELECT count(*) FROM deep_dive_stat_translations t LEFT JOIN deep_dive_stats ds ON ds.id = t.stat_id WHERE ds.id IS NULL = 0

-- ---- and what must stay true afterwards -----------------------------

-- THE FLOOR DROPS FROM THREE TO TWO, and that is a real consequence of
-- this list rather than a loosened check. 643 asserted every country kept
-- at least three tiles; Cyprus loses its B2G receive tile here and is
-- left with two ("2x / Issuance mandates proposed, then dropped" and
-- "2030 / EU cross-border floor"). Two is the new floor and is asserted
-- so the next sweep cannot quietly empty a strip.
--
-- Wrapped in a subquery: the runner splits on the LAST comparison
-- operator, so a bare `... HAVING count(*) < 2 ... = 0` would be read as
-- a query ending `< 2` compared against 0.
-- ASSERT ALWAYS: SELECT (SELECT count(*) FROM (SELECT country_id FROM deep_dive_stats GROUP BY country_id HAVING count(*) < 2)) = 0

-- ASSERT ALWAYS: SELECT count(*) FROM deep_dive_stat_translations t LEFT JOIN deep_dive_stats ds ON ds.id = t.stat_id WHERE ds.id IS NULL = 0
""")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    out = os.path.join(HERE, "644_dan_tile_removals.sql")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(sql())
    print(f"{out}: {len(REMOVE)} tiles")
