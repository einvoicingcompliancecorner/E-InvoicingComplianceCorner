import json

OUT_FILE = "019_malaysia_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/malaysia_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 additional Malaysia stories covering the RM1m")
lines.append("-- permanent exemption threshold and Phase 5 cancellation, the")
lines.append("-- RM10,000 individual-invoice rule, and the Phase 4 relaxation")
lines.append("-- extension to 2027/full enforcement pushed to 2028. Sourced to")
lines.append("-- the official LHDN e-Invoice portal, matching Malaysia's existing")
lines.append("-- stories. Clean content relying on the auto-rendered link system.")
lines.append("-- Generated by migrations/generate_malaysia_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
