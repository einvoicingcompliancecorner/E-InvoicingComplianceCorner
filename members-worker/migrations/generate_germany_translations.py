import json

OUT_FILE = "013_germany_story_translations.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/germany_translations.json', encoding='utf-8') as f:
    translations = json.load(f)

lines = []
lines.append("-- Spanish, German, and French translations for the 3 new Germany")
lines.append("-- stories. INSERT OR IGNORE, safe against the existing English rows.")
lines.append("-- Generated by migrations/generate_germany_translations.py.")
lines.append("")

for story_id, langs in translations.items():
    for lang, content in langs.items():
        lines.append(
            f"INSERT OR IGNORE INTO story_translations (story_id, lang, title, summary, html) VALUES "
            f"('{sql_escape(story_id)}', '{lang}', '{sql_escape(content['title'])}', "
            f"'{sql_escape(content['summary'])}', '{sql_escape(content['html'])}');"
        )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Total INSERT statements: {sum(len(v) for v in translations.values())}")
print(f"Written to {OUT_FILE}")
