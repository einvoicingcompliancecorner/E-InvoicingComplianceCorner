import json

OUT_FILE = "037_canada_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/canada_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Canada stories covering the 2022 federal B2G")
lines.append("-- mandate via SAP Ariba (the only hard requirement), DBNAlliance's")
lines.append("-- growing 2026 momentum as the voluntary North American option, and")
lines.append("-- the active federal/Quebec exploration of a domestic mandate. First")
lines.append("-- stories for Canada, identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official PSPC/Canada.ca portal.")
lines.append("-- Generated by migrations/generate_canada_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
