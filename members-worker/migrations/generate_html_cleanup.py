import json

OUT_FILE = "011_cleanup_embedded_links.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/story_html_updates.json', encoding='utf-8') as f:
    updates = json.load(f)

lines = []
lines.append("-- Cleanup: removes manually-embedded source/deep-dive links from")
lines.append("-- story HTML now that both are auto-rendered by renderIssue() based")
lines.append("-- on the source_url column and story_countries, in the correct order")
lines.append("-- (source link, then deep-dive link(s)). Fixes a real duplicate-link")
lines.append("-- bug affecting 20 of the original 23 stories (source link was both")
lines.append("-- embedded in HTML and auto-rendered from source_url), and corrects")
lines.append("-- the 3 France stories' deep-dive link ordering (was appearing before")
lines.append("-- the source link instead of after).")
lines.append("-- Generated by migrations/generate_html_cleanup.py.")
lines.append("")

for story_id, new_html in updates:
    lines.append(
        f"UPDATE stories SET html_en = '{sql_escape(new_html)}' WHERE id = '{sql_escape(story_id)}';"
    )
    lines.append(
        f"UPDATE story_translations SET html = '{sql_escape(new_html)}' WHERE story_id = '{sql_escape(story_id)}' AND lang = 'en';"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(updates)} story cleanups ({len(updates) * 2} UPDATE statements) to {OUT_FILE}")
