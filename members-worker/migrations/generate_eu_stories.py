import json

OUT_FILE = "033_eu_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/eu_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 European Union stories covering genuinely EU-wide")
lines.append("-- ViDA developments (not tied to any single member state's own")
lines.append("-- implementation): the updated EN 16931-1:2026 standard, the full")
lines.append("-- Commission implementation roadmap through 2035, and the still-open")
lines.append("-- definitional questions around 'real-time' reporting. First stories")
lines.append("-- tagged European Union, identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official European Commission")
lines.append("-- Taxation and Customs Union portal.")
lines.append("-- Generated by migrations/generate_eu_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
