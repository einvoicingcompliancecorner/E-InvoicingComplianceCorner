import json

OUT_FILE = "047_sweden_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/sweden_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Sweden stories covering the February 2026 special")
lines.append("-- investigator appointment (assessing a domestic e-invoicing mandate,")
lines.append("-- findings due Nov 2027), the May 2026 online-audit powers granted to")
lines.append("-- Skatteverket, and the Digg-PTS merger transferring the Peppol")
lines.append("-- Authority function. First stories for Sweden, identified via the")
lines.append("-- country-by-country story-count audit. Sourced to the official")
lines.append("-- Skatteverket portal.")
lines.append("-- Generated by migrations/generate_sweden_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
