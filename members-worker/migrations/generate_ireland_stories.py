import json

OUT_FILE = "041_ireland_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/ireland_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Ireland stories covering the 2019 B2G Peppol")
lines.append("-- mandate anchor, the October 2025 phased domestic B2B mandate")
lines.append("-- announcement (deliberately ahead of the EU's own 2030 deadline),")
lines.append("-- and the February 2026 large-corporate criteria clarification.")
lines.append("-- First stories for Ireland, identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official Revenue.ie portal.")
lines.append("-- Generated by migrations/generate_ireland_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
