import json
import os

REPO_ROOT = "/home/claude/repo"
OUT_FILE = os.path.join(REPO_ROOT, "members-worker", "migrations", "002_backfill_countries.sql")

# Authoritative region groupings, copied exactly from countries.js.
REGIONS = {
    "Europe": ["Belgium", "Croatia", "Denmark", "France", "Germany", "Ireland",
               "Italy", "Norway", "Poland", "Romania", "Slovakia", "Spain",
               "Sweden", "United Kingdom"],
    "Middle East": ["Saudi Arabia", "United Arab Emirates"],
    "Asia-Pacific": ["Australia", "China", "India", "Malaysia", "New Zealand", "Singapore"],
    "Americas": ["Brazil", "Canada", "Chile", "Mexico", "Peru", "United States"],
}

# Standard ISO 3166-1 alpha-2 codes.
ISO_CODES = {
    "Belgium": "BE", "Croatia": "HR", "Denmark": "DK", "France": "FR",
    "Germany": "DE", "Ireland": "IE", "Italy": "IT", "Norway": "NO",
    "Poland": "PL", "Romania": "RO", "Slovakia": "SK", "Spain": "ES",
    "Sweden": "SE", "United Kingdom": "GB",
    "Saudi Arabia": "SA", "United Arab Emirates": "AE",
    "Australia": "AU", "China": "CN", "India": "IN", "Malaysia": "MY",
    "New Zealand": "NZ", "Singapore": "SG",
    "Brazil": "BR", "Canada": "CA", "Chile": "CL", "Mexico": "MX",
    "Peru": "PE", "United States": "US",
}

def sql_escape(s):
    return s.replace("'", "''")

# Pull verified translated names straight from the existing subscribe
# translation files, rather than re-typing them (avoids transcription
# drift from what's already live on the site).
country_translations = {}  # lang -> {english_name: translated_name}
region_translations = {}   # lang -> {english_region: translated_region}
for lang in ["es", "de", "fr"]:
    with open(os.path.join(REPO_ROOT, "i18n", f"{lang}-subscribe.json"), encoding="utf-8") as f:
        data = json.load(f)
    country_translations[lang] = data["countryNames"]
    region_translations[lang] = data["regionNames"]

all_countries = []
for region, countries in REGIONS.items():
    for country in countries:
        all_countries.append((country, region))

lines = []
lines.append("-- Backfill: countries, country_translations, and region translations.")
lines.append("-- Generated by migrations/generate_countries_backfill.py — do not hand-edit.")
lines.append("-- Region translations are stored in the generic `translations` table")
lines.append("-- under namespace='regions', since no dedicated region_translations")
lines.append("-- table was created in the initial schema — a deliberate, documented")
lines.append("-- shortcut rather than an oversight. See D1-MIGRATION-PLAN.md.")
lines.append("")

# countries table
for country, region in all_countries:
    code = ISO_CODES[country]
    lines.append(
        f"INSERT INTO countries (code, name_en, region) VALUES "
        f"('{code}', '{sql_escape(country)}', '{sql_escape(region)}');"
    )
lines.append("")

# country_translations table — English row too, for consistency (so
# every consumer can query lang='en' the same way as any other language,
# rather than needing a special case for "no translation row exists").
for country, region in all_countries:
    code = ISO_CODES[country]
    lines.append(
        f"INSERT INTO country_translations (country_id, lang, display_name) "
        f"SELECT id, 'en', '{sql_escape(country)}' FROM countries WHERE code = '{code}';"
    )
    for lang in ["es", "de", "fr"]:
        translated = country_translations[lang].get(country, country)
        lines.append(
            f"INSERT INTO country_translations (country_id, lang, display_name) "
            f"SELECT id, '{lang}', '{sql_escape(translated)}' FROM countries WHERE code = '{code}';"
        )
lines.append("")

# region translations — generic translations table, namespace='regions'
for region in REGIONS.keys():
    lines.append(
        f"INSERT INTO translations (namespace, key, lang, value) VALUES "
        f"('regions', '{sql_escape(region)}', 'en', '{sql_escape(region)}');"
    )
    for lang in ["es", "de", "fr"]:
        translated = region_translations[lang].get(region, region)
        lines.append(
            f"INSERT INTO translations (namespace, key, lang, value) VALUES "
            f"('regions', '{sql_escape(region)}', '{lang}', '{sql_escape(translated)}');"
        )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Countries: {len(all_countries)}")
print(f"Country translation rows (incl. English): {len(all_countries) * 4}")
print(f"Region translation rows: {len(REGIONS) * 4}")
print(f"Written to {OUT_FILE}")
