"""Generate migration 641 — the menu says which items need an account.

Run:  python3 migrations/gen_menu_subscriber_marker.py
Writes: migrations/641_menu_subscriber_marker.sql, and patches i18n/*.json.

Dan, 24 August 2026: "could you update the menu link under Resources, to
indicate when a menu item is subscriber only. This should not prevent
them from clicking the link, as they will be presented with a subscribe
page thereafter."

THIS UNDOES A DELIBERATE REMOVAL, AND THAT IS THE POINT. A padlock used
to sit on the planner's menu item and was taken off on 21 August 2026,
for a reason the markup still records: it told a signed-out reader
"subscribers only" about a page that was served to everyone. The claim
was false, and a false promise of exclusivity made to the one person it
would turn away is worse than no marker at all.

What changed is the fact underneath it. The planner, the compliance
guides and now the specification register all answer a sign-up wall to a
request without a session -- three `render*Gate` calls in site-worker,
tested by roi-gate.mjs, guides-routes.mjs and spec-register.mjs. So the
marker is true now, and the comment explaining its absence has become
prose describing a world that no longer exists. Both are fixed together.

A WORD, NOT A PADLOCK. The old marker was a glyph. This one is text in
the same treatment as (Beta), for three reasons: it translates, a screen
reader reads it, and the (Beta) colour has already been measured at
5.1:1 at rest and 4.5:1 on hover against BOTH dropdown states -- an
emoji's colour cannot be controlled at all, and the tracker's menus are
not covered by the contrast audit.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
I18N = os.path.join(REPO, "i18n")
LANGS = ["en", "de", "fr", "es"]

# One word if the language has one. This sits at the end of a menu label
# in a dropdown roughly 260px wide; a phrase would wrap the row.
S = {
    "menu.subscriberOnly": {
        "en": "Subscribers",
        "de": "Abonnenten",
        "fr": "Abonnés",
        "es": "Suscriptores",
    },
}


def q(s):
    return "'" + s.replace("'", "''") + "'"


def check():
    problems = []
    for key, vals in S.items():
        for lang in LANGS:
            if not vals.get(lang):
                problems.append(f"{key}: no {lang}")
            elif len(vals[lang]) > 16:
                # Measured, not guessed: the label plus this marker plus
                # the icon has to fit one line of the dropdown.
                problems.append(f"{key}/{lang}: {len(vals[lang])} chars, too long for the row")
    if problems:
        raise SystemExit("REFUSING TO GENERATE:\n  " + "\n  ".join(problems))


HEADER = """-- ================================================================
-- The menu says which items need an account.
-- ================================================================
--
-- Generated by gen_menu_subscriber_marker.py -- edit that, not this.
--
-- Dan, 24 August 2026: "it would be good to highlight this in the menu
-- itself" -- and, in the same breath, that it "should not prevent them
-- from clicking the link, as they will be presented with a subscribe
-- page thereafter". So this is a qualifier on the label, not a state on
-- the link: nothing is disabled, nothing is hidden, and the route still
-- answers the wall it always did.
--
-- IT RESTORES A MARKER THAT WAS DELIBERATELY REMOVED. A padlock came
-- off the planner's menu item on 21 August because it claimed
-- exclusivity for a page then served to everyone. Three routes now
-- genuinely gate -- the planner, the compliance guides and the
-- specification register -- so the claim is true, and the markup
-- comment that explained the padlock's absence has been rewritten
-- rather than left to certify the opposite of what the code does.
-- ================================================================
"""


def sql():
    lines = [HEADER, "-- ---- the string ----------------------------------------------------"]
    for key in sorted(S):
        for lang in LANGS:
            lines.append(
                "INSERT OR REPLACE INTO translations (namespace, key, lang, value)\n"
                f"  VALUES ('tracker', {q(key)}, '{lang}', {q(S[key][lang])});")
    lines.append(f"""
-- ---- what this migration claims it did ------------------------------

-- ASSERT: SELECT count(*) FROM translations WHERE namespace = 'tracker' AND key = 'menu.subscriberOnly' = {len(LANGS)}

-- ---- and what must stay true afterwards -----------------------------

-- FOUR LANGUAGES OR NONE. An English marker on a German menu would be
-- the one word on the row that is not translated, which reads as a
-- system message rather than as part of the label.
-- ASSERT ALWAYS: SELECT count(*) FROM (SELECT key FROM translations WHERE namespace = 'tracker' AND key = 'menu.subscriberOnly' GROUP BY key HAVING count(DISTINCT lang) != 4) = 0

-- AND IT STAYS SHORT. The marker shares a row with an icon and a label
-- inside a narrow dropdown; a phrase here wraps every gated item onto
-- two lines. tests/spec-register.mjs checks the markup; this checks the
-- string a future edit might lengthen without looking at the menu.
-- ASSERT ALWAYS: SELECT count(*) FROM translations WHERE namespace = 'tracker' AND key = 'menu.subscriberOnly' AND length(value) > 16 = 0
""")
    return "\n".join(lines) + "\n"


def patch_i18n():
    for lang in LANGS:
        path = os.path.join(I18N, f"{lang}.json")
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        menu = doc.setdefault("menu", {})
        for key, vals in S.items():
            menu[key.split(".", 1)[1]] = vals[lang]
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(doc, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        print(f"  i18n/{lang}.json: menu.subscriberOnly")


if __name__ == "__main__":
    check()
    out = os.path.join(HERE, "641_menu_subscriber_marker.sql")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(sql())
    print(f"{out}: {len(S)} key x {len(LANGS)} languages")
    patch_i18n()
