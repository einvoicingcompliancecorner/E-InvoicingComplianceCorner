import json

OUT_FILE = "025_italy_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/italy_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Italy stories covering the FatturaPA v1.9.1")
lines.append("-- technical specification update (published, then effective), and")
lines.append("-- the EU derogation timing converging with ViDA's cross-border")
lines.append("-- deadline. First stories for Italy despite one of Europe's most")
lines.append("-- mature clearance systems (SDI, since 2019) -- identified via a")
lines.append("-- full country-by-country story-count audit. Sourced to the")
lines.append("-- official Agenzia delle Entrate portal.")
lines.append("-- Generated by migrations/generate_italy_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
