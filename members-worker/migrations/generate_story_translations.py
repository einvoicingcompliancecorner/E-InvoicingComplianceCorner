import json

OUT_FILE = "/home/claude/repo/members-worker/migrations/008_story_translations.sql"

def sql_escape(s):
    return s.replace("'", "''")

lines = []
lines.append("-- Backfill: Spanish, German, and French translations for all 23")
lines.append("-- existing newsletter stories. Uses INSERT OR IGNORE so it's safe")
lines.append("-- to re-run without conflicting with the existing English rows.")
lines.append("-- Generated by migrations/generate_story_translations.py.")
lines.append("")

for lang, fname in [("es", "/tmp/stories_es.json"), ("de", "/tmp/stories_de.json"), ("fr", "/tmp/stories_fr.json")]:
    with open(fname, encoding="utf-8") as f:
        stories = json.load(f)
    for story_id, content in stories.items():
        lines.append(
            f"INSERT OR IGNORE INTO story_translations (story_id, lang, title, summary, html) VALUES "
            f"('{sql_escape(story_id)}', '{lang}', '{sql_escape(content['title'])}', "
            f"'{sql_escape(content['summary'])}', '{sql_escape(content['html'])}');"
        )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Total INSERT statements: {len(lines) - 4}")
print(f"Written to {OUT_FILE}")
