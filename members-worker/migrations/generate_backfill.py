import json
import os
import re

REPO_ROOT = "/home/claude/repo"
I18N_DIR = os.path.join(REPO_ROOT, "i18n")
OUT_FILE = os.path.join(REPO_ROOT, "members-worker", "migrations", "001_backfill_translations.sql")

LANGS = ["en", "es", "de", "fr"]

# Filename -> namespace mapping. Deliberately excludes *-data.json files
# (tracker per-country regulatory content translations — a different
# kind of thing than page chrome, closer to "stories"; left out of this
# pass on purpose, see accompanying notes).
def namespace_for(filename):
    # Shared tracker chrome: en.json, es.json, de.json, fr.json
    if re.fullmatch(r"(en|es|de|fr)\.json", filename):
        return "tracker"
    m = re.fullmatch(r"(en|es|de|fr)-(.+)\.json", filename)
    if m:
        suffix = m.group(2)
        if suffix == "data":
            return None  # excluded — handled separately, see notes
        return suffix  # "subscribe", "feedback", "edu-mandate-types", etc.
    return None

def lang_for(filename):
    m = re.match(r"(en|es|de|fr)", filename)
    return m.group(1) if m else None

def sql_escape(s):
    return s.replace("'", "''")

def flatten(obj, prefix=""):
    """Yield (dot.notation.key, value) for every leaf string, skipping
    _meta, and skipping countryNames/regionNames entirely (those are
    migrated separately into the dedicated countries/regions tables,
    not duplicated again inside generic page-chrome translations —
    that duplication is exactly what this migration exists to fix)."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if prefix == "" and k in ("_meta", "countryNames", "regionNames"):
                continue
            new_prefix = f"{prefix}.{k}" if prefix else k
            yield from flatten(v, new_prefix)
    elif isinstance(obj, list):
        for i, item in enumerate(obj):
            yield from flatten(item, f"{prefix}.{i}")
    else:
        if obj is not None and str(obj).strip() != "":
            yield (prefix, str(obj))

rows = []  # (namespace, key, lang, value)
skipped_files = []
included_files = []

for filename in sorted(os.listdir(I18N_DIR)):
    if not filename.endswith(".json"):
        continue
    ns = namespace_for(filename)
    lang = lang_for(filename)
    if ns is None or lang is None:
        skipped_files.append(filename)
        continue
    included_files.append((filename, ns, lang))
    with open(os.path.join(I18N_DIR, filename), encoding="utf-8") as f:
        data = json.load(f)
    for key, value in flatten(data):
        rows.append((ns, key, lang, value))

print(f"Included {len(included_files)} files, skipped {len(skipped_files)} (data-array files, excluded on purpose):")
for f in skipped_files:
    print(f"  skipped: {f}")
print(f"Total translation rows generated: {len(rows)}")

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("-- Backfill: page-chrome translations (tracker, subscribe, feedback,\n")
    out.write("-- education pages) migrated from existing i18n/*.json files.\n")
    out.write("-- Generated by migrations/generate_backfill.py — do not hand-edit.\n")
    out.write("-- Deliberately excludes *-data.json (tracker per-country content\n")
    out.write("-- translations) — see D1-MIGRATION-PLAN.md.\n\n")
    for ns, key, lang, value in rows:
        out.write(
            f"INSERT INTO translations (namespace, key, lang, value) VALUES "
            f"('{sql_escape(ns)}', '{sql_escape(key)}', '{sql_escape(lang)}', '{sql_escape(value)}');\n"
        )

print(f"Written to {OUT_FILE}")
