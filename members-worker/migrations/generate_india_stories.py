import json

OUT_FILE = "029_india_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/india_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 India stories covering the mandatory QR-code-on-paper")
lines.append("-- tightening, the strictly-enforced 30-day IRN reporting window for")
lines.append("-- large taxpayers, and the ongoing threshold-reduction discussion.")
lines.append("-- First stories for India -- one of the largest e-invoicing regimes")
lines.append("-- in the world by transaction volume -- identified via the")
lines.append("-- country-by-country story-count audit. Sourced to the official")
lines.append("-- GST Invoice Registration Portal (einvoice1.gst.gov.in).")
lines.append("-- Generated by migrations/generate_india_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
