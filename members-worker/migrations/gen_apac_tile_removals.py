import os

HERE = os.path.dirname(os.path.abspath(__file__))

REMOVE = [
    ('Australia', 'No B2B', 'Mandate — voluntary only'),
    ('Australia', '2022', 'B2G receiving mandate since'),
    ('Azerbaijan', '1 Apr 2017', 'The e-qaimə mandate begins, under Tax Code Article 71-1'),
    ('China', 'Dec 2024', 'Nationwide since'),
    ('India', '2020', 'Mandatory since October'),
    ('Indonesia', '1 Jul 2016', 'e-Faktur becomes mandatory nationwide'),
    ('Indonesia', '1 Jan 2025', 'Coretax platform launches'),
    ('Japan', 'Voluntary', 'JP PINT/Peppol e-invoicing adoption'),
    ('Kazakhstan', '2014', 'IS ESF launches as a voluntary pilot -- 12 years of history by the 2026 expansion'),
    ('Kazakhstan', '1 Jan 2019', 'E-invoicing becomes mandatory for all VAT-registered taxpayers'),
    ('Pakistan', '31 Dec 2025', 'Formal deadline for all registered persons to integrate'),
    ('Philippines', '2018', 'TRAIN Law establishes the legal basis (RA 10963)'),
    ('Singapore', '2018', 'First Peppol Authority outside Europe'),
    ('Taiwan', '1 May 2017', 'Cross-border VAT/eGUI regime for foreign digital providers begins'),
    ('Uzbekistan', '1 Jan 2020', 'Electronic invoicing becomes mandatory for all business entities'),
]


def q(s):
    return "'" + s.replace("'", "''") + "'"


HEADER = """-- ================================================================
-- Dan's Asia-Pacific tile removals -- the last regional pass.
-- ================================================================
--
-- Generated by gen_apac_tile_removals.py -- edit that, not this.
--
-- Fifteen tiles. Most are dated milestones restating a headline tile;
-- Australia's and Japan's are the status word itself sitting under a
-- mandate tile printing the same word, which 643's rule missed because
-- "No B2B" is a value carrying half of its own label. Singapore's Peppol
-- history and the Philippines' TRAIN Law citation duplicate nothing and
-- are here on judgement, like Qatar's VAT tile in 646.
--
-- With this pass: 90 tiles removed of the original 354, 264 left.
-- ================================================================
"""


def sql():
    out = [HEADER, "-- ---- the removals -------------------------------------------------"]
    for country, value, label in REMOVE:
        out.append(f"\n-- {country}: {value} / {label}")
        out.append(
            "DELETE FROM deep_dive_stat_translations WHERE stat_id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    JOIN deep_dive_stat_translations t ON t.stat_id = ds.id AND t.lang = 'en'\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_label = {q(label)});")
        out.append(
            "DELETE FROM deep_dive_stats WHERE id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    LEFT JOIN deep_dive_stat_translations t ON t.stat_id = ds.id\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_id IS NULL);")

    out.append(f"""
-- ---- what this migration claims it did ------------------------------

-- {len(REMOVE)} tiles named above, from 279, leaving 264.
-- ASSERT: SELECT count(*) FROM deep_dive_stats = 264

-- Every language went with them; no orphaned translation rows.
-- ASSERT: SELECT count(*) FROM deep_dive_stat_translations t LEFT JOIN deep_dive_stats ds ON ds.id = t.stat_id WHERE ds.id IS NULL = 0

-- CYPRUS IS STILL THE ONLY COUNTRY AT TWO. Australia, Indonesia,
-- Kazakhstan and Japan each lose enough to reach three, and three of
-- those lose two tiles apiece -- so the floor is checked here rather
-- than assumed to have survived a fourth pass.
-- ASSERT: SELECT (SELECT count(*) FROM (SELECT country_id FROM deep_dive_stats GROUP BY country_id HAVING count(*) < 3)) = 1
""")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    out = os.path.join(HERE, "647_apac_tile_removals.sql")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(sql())
    print(f"{out}: {len(REMOVE)} tiles")
