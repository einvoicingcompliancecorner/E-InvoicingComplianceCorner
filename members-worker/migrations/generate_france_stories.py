import json

OUT_FILE = "009_france_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/france_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: three real, sourced newsletter stories covering France's")
lines.append("-- e-invoicing mandate developments through 2026 ahead of the 1 September")
lines.append("-- go-live — the PPF pilot opening, DGFiP's no-delay confirmation with")
lines.append("-- soft-landing enforcement, and current readiness statistics.")
lines.append("-- Each includes a link to the France Deep Dive, per the new standing")
lines.append("-- convention for all stories going forward.")
lines.append("-- Generated by migrations/generate_france_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
