import json

OUT_FILE = "027_uk_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/uk_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 United Kingdom stories covering the Autumn Budget")
lines.append("-- 2025 mandate confirmation, the June 2026 Peppol network confirmation,")
lines.append("-- and the genuinely open design questions still pending ahead of the")
lines.append("-- Budget 2026 implementation roadmap. First stories for the UK,")
lines.append("-- identified via the country-by-country story-count audit. Sourced")
lines.append("-- to the official GOV.UK consultation response page.")
lines.append("-- Generated by migrations/generate_uk_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
