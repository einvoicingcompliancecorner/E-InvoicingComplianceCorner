import json

OUT_FILE = "039_us_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/us_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 United States stories covering the 2018 federal")
lines.append("-- B2G requirement via Treasury's IPP (format never mandated, unlike")
lines.append("-- Canada), the 2024 US-EU joint declaration on e-invoicing")
lines.append("-- interoperability, and the practical record-keeping requirements")
lines.append("-- that apply even with no B2B mandate. Final country in the current")
lines.append("-- gap-filling batch, identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official Treasury IPP portal.")
lines.append("-- Generated by migrations/generate_us_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
