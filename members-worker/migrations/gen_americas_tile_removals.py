"""Generate migration 648 -- Dan's Americas removals, and the last of them.

Run:  python3 migrations/gen_americas_tile_removals.py
Writes: migrations/648_americas_tile_removals.sql

The fifth pass and the end of the sweep. 643 swept by rule; Dan then read
every page region by region -- Europe and the Americas (644), Middle East
/ Africa (646), Asia-Pacific (647), and now the Latin American countries
644 did not reach.

---- LATIN AMERICA IS WHERE THIS PATTERN IS THICKEST -------------------

Eight of the nine are a founding date restating a headline tile: Mexico's
"2014 / CFDI mandatory since", Ecuador's "Since 2014", Uruguay's 2012
decree and its 2025 universal-issuance date, Argentina's and Colombia's
first mandatory waves, Costa Rica's completed general mandate, the
Dominican Republic's Ley 32-23. These are the oldest continuous
e-invoicing regimes in the world, so almost every one of their pages led
with the year it started -- directly above a B2B tile already reading
ACTIVE.

The dates are not lost. Every one is in the compliance timeline further
down the same page, which is where a founding date belongs: it explains
how a country got here, and the strip is for what is true now.

CANADA'S IS THE OTHER KIND -- "No B2B / Federal mandate -- none" is the
status word itself under a mandate tile printing NO MANDATE, the same
shape as Australia's and Japan's in 647, and missed by 643's rule for the
same reason: the value carries half of its own label.

---- WHAT THE WHOLE SWEEP COST AND WHAT IT REMOVED --------------------

  643  rules     43 tiles
  644  Dan       24
  646  Dan        8
  647  Dan       15
  648  Dan        9
                ---
                 99 of 354, leaving 255.

The rules found 43 and were never going to find the other 56. That is not
a criticism of them: they cleared the mechanical cases in one pass and
made the remainder small enough for a person to read. But the durable
lesson is the one 647 recorded -- prose does not divide tidily into a
value column and a label column, and a rule that assumes it does will
keep missing "No B2B / Federal mandate -- none" forever.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

REMOVE = [
    ('Argentina', '2015', 'First mandatory wave -- VAT-registered taxpayers'),
    ('Canada', 'No B2B', 'Federal mandate — none'),
    ('Colombia', '2018', 'First mandatory wave -- large taxpayers'),
    ('Costa Rica', '1 Nov 2018', 'General mandate completed for all remaining VAT taxpayers'),
    ('Dominican Republic', '16 May 2023', 'Ley 32-23 promulgated, establishing the mandatory e-CF regime'),
    ('Ecuador', 'Since 2014', 'Near-real-time e-invoicing has been required'),
    ('Mexico', '2014', 'CFDI mandatory since'),
    ('Uruguay', '1 Jan 2025', 'Universal mandatory CFE issuance for all VAT taxpayers'),
    ('Uruguay', '2012', 'Year DGI created the CFE regime (Decreto 36/012)'),
]


def q(s):
    return "'" + s.replace("'", "''") + "'"


HEADER = """-- ================================================================
-- Dan's Americas tile removals -- the last of the sweep.
-- ================================================================
--
-- Generated by gen_americas_tile_removals.py -- edit that, not this.
--
-- Nine tiles. Eight are a founding date restating a headline tile, which
-- is thickest here because Latin America runs the oldest continuous
-- e-invoicing regimes in the world and nearly every page led with the
-- year it started -- directly above a B2B tile already reading ACTIVE.
-- The dates stay in each page's compliance timeline, where a founding
-- date belongs; the strip is for what is true now.
--
-- Canada's "No B2B / Federal mandate -- none" is the other kind: the
-- status word itself under a tile printing NO MANDATE.
--
-- Totals across the five passes: 99 of 354 removed, 255 left.
-- ================================================================
"""


def sql():
    out = [HEADER, "-- ---- the removals -------------------------------------------------"]
    for country, value, label in REMOVE:
        out.append(f"\n-- {country}: {value} / {label}")
        out.append(
            "DELETE FROM deep_dive_stat_translations WHERE stat_id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    JOIN deep_dive_stat_translations t ON t.stat_id = ds.id AND t.lang = 'en'\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_label = {q(label)});")
        out.append(
            "DELETE FROM deep_dive_stats WHERE id IN (\n"
            "  SELECT ds.id FROM deep_dive_stats ds\n"
            "    JOIN countries c ON c.id = ds.country_id\n"
            "    LEFT JOIN deep_dive_stat_translations t ON t.stat_id = ds.id\n"
            f"   WHERE c.name_en = {q(country)} AND t.stat_id IS NULL);")

    out.append(f"""
-- ---- what this migration claims it did ------------------------------

-- {len(REMOVE)} tiles named above, from 264, leaving 255.
-- ASSERT: SELECT count(*) FROM deep_dive_stats = 255

-- Every language went with them; no orphaned translation rows.
-- ASSERT: SELECT count(*) FROM deep_dive_stat_translations t LEFT JOIN deep_dive_stats ds ON ds.id = t.stat_id WHERE ds.id IS NULL = 0

-- CYPRUS IS STILL THE ONLY COUNTRY AT TWO, after five passes and 99
-- removals. Uruguay loses two here and four countries land exactly on
-- three, so this is checked rather than assumed for the fifth time.
-- ASSERT: SELECT (SELECT count(*) FROM (SELECT country_id FROM deep_dive_stats GROUP BY country_id HAVING count(*) < 3)) = 1

-- ---- and what must stay true afterwards -----------------------------

-- NO COUNTRY EVER LOSES ITS WHOLE STRIP. The floor has been two since
-- 644; restating it here means the invariant survives with the last
-- migration of the sweep rather than with the middle of it.
-- ASSERT ALWAYS: SELECT (SELECT count(*) FROM (SELECT country_id FROM deep_dive_stats GROUP BY country_id HAVING count(*) < 2)) = 0
""")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    out = os.path.join(HERE, "648_americas_tile_removals.sql")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(sql())
    print(f"{out}: {len(REMOVE)} tiles")
