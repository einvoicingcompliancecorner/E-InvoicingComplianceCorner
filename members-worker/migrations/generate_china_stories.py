import json

OUT_FILE = "035_china_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/china_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 China stories covering the VAT Law taking effect")
lines.append("-- (embedding e-fapiao directly into tax legislation), the regional")
lines.append("-- paper invoice phase-out pattern (Dalian as a representative")
lines.append("-- example), and operational realities around mandatory acceptance")
lines.append("-- and decades-long archiving. First stories for China -- one of the")
lines.append("-- world's largest e-invoicing regimes -- identified via the")
lines.append("-- country-by-country story-count audit. Sourced to the official")
lines.append("-- State Taxation Administration portal.")
lines.append("-- Generated by migrations/generate_china_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
