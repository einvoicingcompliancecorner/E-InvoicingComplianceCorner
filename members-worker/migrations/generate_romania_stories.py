import json

OUT_FILE = "031_romania_stories.sql"

def sql_escape(s):
    return s.replace("'", "''")

with open('/tmp/romania_stories.json', encoding='utf-8') as f:
    stories = json.load(f)

lines = []
lines.append("-- New stories: 3 Romania stories covering the January 2026 scope")
lines.append("-- expansion + working-days transmission deadline shift, Law No. 88's")
lines.append("-- two-directional scope changes (farmers exempted, NGOs mandated),")
lines.append("-- and the SME enforcement deadline arriving 1 July 2026. First")
lines.append("-- stories for Romania -- RO e-Factura has been a genuine clearance")
lines.append("-- system since 2024 -- identified via the country-by-country")
lines.append("-- story-count audit. Sourced to the official Ministry of Finance")
lines.append("-- e-Factura portal.")
lines.append("-- Generated by migrations/generate_romania_stories.py.")
lines.append("")

for s in stories:
    lines.append(
        f"INSERT INTO stories (id, date, month, summary_en, html_en, source_url, published) VALUES "
        f"('{sql_escape(s['id'])}', '{s['date']}', '{s['month']}', "
        f"'{sql_escape(s['summary'])}', '{sql_escape(s['html'])}', '{sql_escape(s['source_url'])}', 1);"
    )
    for country in s["countries"]:
        lines.append(
            f"INSERT INTO story_countries (story_id, country_id) "
            f"SELECT '{sql_escape(s['id'])}', id FROM countries WHERE name_en = '{sql_escape(country)}';"
        )
    lines.append(
        f"INSERT INTO story_translations (story_id, lang, title, summary, html) VALUES "
        f"('{sql_escape(s['id'])}', 'en', '{sql_escape(s['title'])}', '{sql_escape(s['summary'])}', '{sql_escape(s['html'])}');"
    )

with open(OUT_FILE, "w", encoding="utf-8") as out:
    out.write("\n".join(lines) + "\n")

print(f"Written {len(stories)} stories to {OUT_FILE}")
